"""build-garden.py — render "Every door in the garden" into index.html at BUILD time.

    python3 tools/build-garden.py            # fetch the live atlas, render, write index.html
    python3 tools/build-garden.py --check    # render only; exit 0 if index.html is already current
    python3 tools/build-garden.py --atlas registry.json --constellations tools/constellations.json

Sources (both public):
  * the door atlas   https://myagentohana.com/doors/registry.json   — the ONLY count we quote (summary.public)
  * the constellations (vendored copy of /shared/kb/public/universe/constellations.json, CC BY-SA 4.0):
    every public door placed in one of six constellations; HELD doors are counted but never named.

FAIL CLOSED: if named doors + held doors ≠ summary.public, or a public door has no constellation,
nothing is written and the exit code is non-zero. Numbers must add up.
The generated block lives between the GARDEN-DOORS:BEGIN / END markers; never edit it by hand.
"""
import argparse, datetime as dt, hashlib, html, json, os, re, sys, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ATLAS_URL = "https://myagentohana.com/doors/registry.json"
PUBLIC_KINDS = ("primary", "alias", "subpath", "hub", "taurlink")  # = atlas summary.public
BEGIN = "<!-- GARDEN-DOORS:BEGIN — generated by tools/build-garden.py from the living door atlas; do not edit by hand -->"
END = "<!-- GARDEN-DOORS:END -->"
ORDER = ["music", "gatherings", "memory", "tools", "agents", "gifts"]
KIND_WORD = {"primary": "front door", "alias": "alias", "subpath": "room", "hub": "hub", "taurlink": "hosted door"}


def load(src):
    if re.match(r"https?://", src):
        req = urllib.request.Request(src, headers={"User-Agent": "infinite-garden build (aloha@myagentohana.com)"})
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)
    with open(src, encoding="utf-8") as f:
        return json.load(f)


def esc(x):
    return html.escape(str(x or ""), quote=True)


def label(e):
    u = e["url"]
    host, _, path = u.split("//", 1)[1].partition("/")
    if e["kind"] == "taurlink":
        return e["name"] + " · hosted"
    path = "/" + path if path and path != "/" else ""
    return host + path.rstrip("/") + ("/" if path else "")


def clean_title(t, lab):
    t = re.sub(r"\s+", " ", t or "").strip()
    t = re.sub(r"\s*[·|—–-]\s*(My Agent ʻOhana|Open Source Orchestra 🎻?|Shaka Lei Kaumaka)\s*$", "", t)
    if not t or t.lower() == lab.lower():
        return "an open door of the ʻohana"
    return t[:110]


def render(atlas, cons):
    doors = [e for e in atlas["entries"] if e.get("kind") in PUBLIC_KINDS]
    public = atlas["summary"]["public"]
    if len(doors) != public:
        raise SystemExit(f"FAIL CLOSED: atlas lists {len(doors)} public doors but summary.public = {public}")
    place = {d["url"]: d["constellation"] for d in cons["doors"] if d.get("url")}
    held_by = {c["id"]: int(c.get("held", 0)) for c in cons["constellations"]}
    cons_held = sum(held_by.values())  # held by the constellations file itself (no url there)
    groups = {c["id"]: [] for c in cons["constellations"]}
    # tools/held-keys.json: sha256(url)[:16] of atlas doors the archive consent filter seals — counted, never named here
    hk_path = os.path.join(HERE, "held-keys.json")
    held_keys = set(json.load(open(hk_path, encoding="utf-8"))["keys"]) if os.path.exists(hk_path) else set()
    unplaced = []
    for e in doors:
        c = place.get(e["url"])
        if c is None:
            unplaced.append(e["url"])
        elif hashlib.sha256(e["url"].encode("utf-8")).hexdigest()[:16] in held_keys:
            held_by[c] += 1
        else:
            groups[c].append(e)
    named = sum(len(v) for v in groups.values())
    held = sum(held_by.values())
    if named + held != public:
        raise SystemExit(f"FAIL CLOSED: named {named} + held {held} = {named + held} ≠ summary.public {public} "
                         f"(unplaced {len(unplaced)}: {unplaced[:5]}). Re-run constellations.py on the current atlas.")
    if len(unplaced) != cons_held:
        raise SystemExit(f"FAIL CLOSED: {len(unplaced)} doors without a constellation but {cons_held} held in constellations.json — they must match")
    at = atlas.get("at", "")[:10]
    gen = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d")
    out = [BEGIN,
           '<section class="section garden-doors" id="garden" aria-labelledby="garden-title">',
           '  <div class="wrap">',
           '    <div class="section-heading centered"><p class="eyebrow">Forever a part of the infinite garden</p>'
           '<h2 id="garden-title">Every door<br><em>in the garden</em></h2>'
           f'<p><strong>{public} public doors</strong>, counted by the living <a href="https://myagentohana.com/doors/" target="_blank" rel="noopener noreferrer">door atlas</a> on {esc(at)} — '
           f'{named} named here and {held} counted but named only with their owners’ yes. '
           'Six constellations, one goal: leave every gathering more open, more musical and more alive than we found it.</p></div>',
           '    <div class="garden-constellations">']
    for cid in ORDER:
        c = next(x for x in cons["constellations"] if x["id"] == cid)
        rows = sorted(groups[cid], key=lambda e: (PUBLIC_KINDS.index(e["kind"]), label(e)))
        n_named, n_held = len(rows), held_by[cid]
        total = n_named + n_held
        if total != int(c["count"]):
            raise SystemExit(f"FAIL CLOSED: constellation {cid}: {total} ≠ published count {c['count']}")
        out.append(f'      <details class="garden-constellation" id="garden-{esc(cid)}">')
        out.append(f'        <summary><span class="garden-emoji" aria-hidden="true">{esc(c["emoji"])}</span><span class="garden-name">{esc(c["name"])}</span>'
                   f'<small>{total} door{"s" if total != 1 else ""}{f" · {n_held} held" if n_held else ""}</small><span class="garden-line">{esc(c["line"])}</span></summary>')
        out.append('        <ul class="garden-list">')
        for e in rows:
            lab = label(e)
            out.append(f'          <li><a href="{esc(e["url"])}" target="_blank" rel="noopener noreferrer">{esc(lab)}</a>'
                       f'<span>{esc(clean_title(e.get("title"), lab))} <i>· {KIND_WORD[e["kind"]]}</i></span></li>')
        out.append('        </ul>')
        if n_held:
            out.append(f'        <p class="garden-held">+ {n_held} door{"s" if n_held != 1 else ""} counted here but named only with {"its owner’s" if n_held == 1 else "their owners’"} yes — '
                       'consent before people, always.</p>')
        out.append('      </details>')
    out += ['    </div>',
            f'    <p class="garden-note">Every door above is Shaka-created and open: code under GPL-3.0, words and art under CC BY-SA 4.0, counted by the atlas, '
            'kept by the <a href="https://myagentohana.com/doors/#archive" target="_blank" rel="noopener noreferrer">family archive</a> and the Wayback Machine. '
            f'Section built {gen} from the atlas + the <a href="tools/constellations.json">constellations</a> (CC BY-SA 4.0) by the AI ʻohana — '
            'a machine wrote this list; a human blessed the doors.</p>',
            '  </div>', '</section>', END]
    return "\n".join(out), {"public": public, "named": named, "held": held, "per": {k: len(v) for k, v in groups.items()}}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--atlas", default=ATLAS_URL)
    ap.add_argument("--constellations", default=os.path.join(HERE, "constellations.json"))
    ap.add_argument("--index", default=os.path.join(ROOT, "index.html"))
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if index.html is stale")
    a = ap.parse_args()
    atlas, cons = load(a.atlas), load(a.constellations)
    block, counts = render(atlas, cons)
    page = open(a.index, encoding="utf-8").read()
    if BEGIN in page and END in page:
        new = page[:page.index(BEGIN)] + block + page[page.index(END) + len(END):]
    else:
        anchor = '    <section class="section tribute" id="tribute"'
        if anchor not in page:
            raise SystemExit("FAIL CLOSED: no markers and no tribute anchor in index.html")
        new = page.replace(anchor, block.replace("\n", "\n    ") + "\n\n" + anchor, 1)
    if a.check:
        print(json.dumps(counts), "current" if new == page else "STALE")
        return 0 if new == page else 1
    if new != page:
        open(a.index, "w", encoding="utf-8").write(new)
    print(json.dumps({**counts, "written": new != page}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
